import { useLazyQuery, useQuery } from '@apollo/client';

import { useVideoContext } from '@js/common/video-player/context';

import { isFromPublicSharePage } from '@js/utilities/url';

import { routingUtils, urlUtils } from '@loomhq/shared-utilities';
import { EntityRoutingHeader } from '@loomhq/shared-utilities/constants/siteEntities';
