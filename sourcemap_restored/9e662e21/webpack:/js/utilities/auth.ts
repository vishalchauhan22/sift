function isOAuthData(parsedObj: unknown): parsedObj is OAuthData {
  return (
    typeof parsedObj === 'object' &&
    parsedObj !== null &&
    'created' in parsedObj &&
    typeof parsedObj.created === 'boolean' &&
    'error' in parsedObj &&
    (typeof parsedObj.error === 'string' || parsedObj.error === null) &&
    'loginSuccess' in parsedObj &&
    typeof parsedObj.loginSuccess === 'boolean' &&
    'type' in parsedObj &&
    typeof parsedObj.type === 'string' &&
    'userRole' in parsedObj &&
    typeof parsedObj.userRole === 'string' &&
    ('redirect_after' in parsedObj
      ? typeof parsedObj['redirect_after'] === 'string'
      : true)
  );
}

const updateUserProperty = countryCode => {
  const gqlClient = getGraphQLClient();

  gqlClient
    .mutate({
      mutation: UpdateUserProperty,
      variables: {
        name: UserPropertyEnum.SIGNUP_LOCATION,
        value: countryCode,
      },
    })
    .then(({ data }) => {
      const { success } = data;

      return success;
    });
};

const signupLocationCallback = () => {
  try {
    getLocation()
      .then(location => {
        updateUserProperty(location.country);
      })
      .catch(error => {
        logger.warning(error, {
          message: 'Failed to get update location',
          team: Team.Billing,
        });
      });
  } catch (err) {
    logger.warning(err, {
      message: 'Failed to get fetch location',
      team: Team.Billing,
    });
  }
};

